# Rebuild the gzip C arrays from the original editable pages plus the overlay.
$ErrorActionPreference = 'Stop'
$projectPath = Split-Path $PSScriptRoot -Parent
$webPath = Join-Path $projectPath 'web'
$overlay = Get-Content -LiteralPath (Join-Path $webPath 'camera_overlay.html') -Raw
$output = [Text.StringBuilder]::new()
[void]$output.AppendLine('// Generated by tools/rebuild_camera_pages.ps1; edit web/ sources.')
foreach ($sensor in @('ov2640','ov3660','ov5640')) {
    $html = Get-Content -LiteralPath (Join-Path $webPath "index_$sensor.html") -Raw
    if (-not $html.Contains('</body>')) { throw "Missing body in $sensor page" }
    $html = $html.Replace('</body>', $overlay + [Environment]::NewLine + '</body>')
    $raw = [Text.Encoding]::UTF8.GetBytes($html)
    $memory = [IO.MemoryStream]::new()
    $gzip = [IO.Compression.GZipStream]::new($memory,[IO.Compression.CompressionMode]::Compress,$true)
    $gzip.Write($raw,0,$raw.Length)
    $gzip.Dispose()
    $bytes = $memory.ToArray()
    $memory.Dispose()
    # Verify each generated gzip round-trips before writing the header.
    $reader = [IO.StreamReader]::new([IO.Compression.GZipStream]::new([IO.MemoryStream]::new($bytes),[IO.Compression.CompressionMode]::Decompress))
    $roundTrip = $reader.ReadToEnd()
    $reader.Dispose()
    if ($roundTrip -cne $html) { throw "Gzip verification failed for $sensor" }
    if ([regex]::Matches($roundTrip, "overlay.id = 'sampling-overlay'").Count -ne 1) { throw 'Expected one overlay per page' }
    $name = "index_${sensor}_html_gz"
    [void]$output.AppendLine("#define ${name}_len $($bytes.Length)")
    [void]$output.AppendLine("const uint8_t $name[] = {")
    for ($i = 0; $i -lt $bytes.Length; $i += 16) {
        $end = [Math]::Min($i + 15,$bytes.Length - 1)
        $line = ($bytes[$i..$end] | ForEach-Object { '0x{0:X2}' -f $_ }) -join ', '
        [void]$output.AppendLine("  $line,")
    }
    [void]$output.AppendLine('};')
}
[IO.File]::WriteAllText((Join-Path $projectPath 'camera_index.h'),$output.ToString(),[Text.UTF8Encoding]::new($false))
Write-Output 'Verified all three generated camera pages.'